<header class="legal-intro">
    <h1>Politique de confidentialité</h1>
    <p>Cette politique explique quelles données personnelles sont utilisées par la PNMG, pourquoi elles le sont et comment les personnes concernées peuvent exercer leurs droits.</p>
    <div class="legal-meta">Version en vigueur : 23 septembre 2026</div>
</header>

<h2>1. Responsable du traitement</h2>
<p>Le responsable du traitement est l’administration publique qui exploite la Plateforme Nationale de Mobilité du Gabon. Les coordonnées institutionnelles officielles sont communiquées dans l’espace utilisateur et par l’autorité de tutelle. Elles doivent être utilisées pour toute demande concernant les données personnelles.</p>

<h2>2. Données traitées</h2>
<p>Selon le parcours et le rôle de l’utilisateur, la plateforme peut traiter :</p>
<ul>
    <li>les informations d’identité et de contact des représentants, employés et agents habilités ;</li>
    <li>les informations administratives des compagnies, agences et moyens de transport ;</li>
    <li>les justificatifs déposés et les informations qu’ils contiennent ;</li>
    <li>les rôles, permissions, décisions et historiques de traitement ;</li>
    <li>les données techniques de sécurité, telles que les dates de connexion, l’adresse réseau et les événements d’audit.</li>
</ul>
<p>La PNMG ne demande pas et ne stocke pas directement de numéro complet de carte bancaire, de cryptogramme ou d’identifiant bancaire secret.</p>

<h2>3. Finalités</h2>
<p>Les données sont utilisées pour enregistrer et instruire les dossiers, vérifier la conformité documentaire, gérer les habilitations, sécuriser les accès, prévenir les abus, assurer la traçabilité administrative, produire les notifications utiles et répondre aux obligations applicables au service public concerné.</p>

<h2>4. Fondements du traitement</h2>
<p>Les traitements reposent, selon leur nature, sur l’exécution d’une mission d’intérêt public, le respect d’obligations légales ou réglementaires, la gestion de la relation avec l’usager et la sécurité légitime du service. Lorsqu’un traitement facultatif exige un consentement, celui-ci est demandé séparément et peut être retiré.</p>

<h2>5. Destinataires</h2>
<p>Les données sont accessibles uniquement aux agents et utilisateurs habilités selon leur rôle, ainsi qu’aux prestataires techniques strictement nécessaires et encadrés. Elles ne sont ni vendues ni louées. Une transmission peut avoir lieu lorsqu’elle est exigée par une autorité compétente ou par le droit applicable.</p>

<h2>6. Conservation</h2>
<p>Les données sont conservées pendant la durée nécessaire à l’instruction, à la gestion du dossier, aux obligations d’archivage et à la défense des droits de l’administration ou des usagers. Les journaux de sécurité sont conservés pendant une durée limitée et font l’objet d’une purge programmée. À l’issue des durées applicables, les données sont supprimées, anonymisées ou archivées selon les règles en vigueur.</p>

<h2>7. Sécurité</h2>
<p>La PNMG applique des mesures de contrôle d’accès, de limitation des tentatives, de journalisation, de chiffrement des échanges, de cloisonnement des fichiers et de vérification des téléversements. Aucun dispositif ne supprimant totalement le risque, les droits accordés aux comptes doivent rester limités au besoin réel.</p>

<h2>8. Cookies et mesure d’audience</h2>
<p>La plateforme utilise uniquement les traceurs techniques indispensables au fonctionnement de la session et à la sécurité. Aucun outil publicitaire ni outil de mesure d’audience non essentiel n’est activé dans la version actuelle. Une interface de consentement sera mise en place avant tout ajout de traceur soumis au consentement.</p>

<h2>9. Droits des personnes</h2>
<p>Dans les limites prévues par le droit applicable et les missions de la plateforme, une personne peut demander l’accès à ses données, leur rectification, leur effacement ou la limitation de leur traitement, et faire valoir son opposition lorsqu’elle est applicable. Une preuve d’identité peut être demandée afin d’éviter toute divulgation à un tiers.</p>

<h2>10. Exercer ses droits</h2>
<p>Les demandes doivent être adressées à l’administration de la PNMG par les coordonnées officielles disponibles dans l’espace utilisateur ou auprès de l’autorité de tutelle. La demande doit décrire précisément les données ou le compte concerné. En cas de difficulté persistante, la personne peut saisir l’autorité de protection des données compétente.</p>

<h2>11. Mise à jour</h2>
<p>Cette politique peut évoluer avec le service ou le cadre applicable. Toute nouvelle version indique sa date d’entrée en vigueur en tête de page.</p>
